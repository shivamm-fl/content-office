import { readdir, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";

export async function generateSource(teamsDir = "teams", out = "apps/api/src/teams.generated.ts") {
  const folders = await readdir(teamsDir, { withFileTypes: true });
  const slugs = [];
  for (const folder of folders) {
    if (!folder.isDirectory() || !/^[a-z][a-z0-9-]*$/.test(folder.name)) continue;
    try {
      const files = await readdir(path.join(teamsDir, folder.name));
      if (files.includes("team.json")) slugs.push(folder.name);
    } catch { /* a removed folder */ }
  }
  slugs.sort((a, b) => a === "learnai" ? -1 : b === "learnai" ? 1 : a.localeCompare(b));
  const lines = ["// Generated by tools/gen_teams.mjs. Do not edit by hand."];
  for (const [i, slug] of slugs.entries()) {
    const relative = path.relative(path.dirname(out), path.join(teamsDir, slug, "team.json")).replaceAll("\\", "/");
    lines.push(`import team${i} from ${JSON.stringify(relative.startsWith(".") ? relative : `./${relative}`)};`);
  }
  lines.push("", `export const GENERATED_TEAMS = [${slugs.map((_, i) => `team${i}`).join(", ")}] as const;`, "");
  return lines.join("\n");
}

export async function generate(teamsDir = "teams", out = "apps/api/src/teams.generated.ts") {
  const source = await generateSource(teamsDir, out);
  await writeFile(out, source);
  return source;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const arg = (name, fallback) => {
    const i = process.argv.indexOf(name);
    return i < 0 ? fallback : process.argv[i + 1];
  };
  await generate(arg("--teams-dir", "teams"), arg("--out", "apps/api/src/teams.generated.ts"));
}
